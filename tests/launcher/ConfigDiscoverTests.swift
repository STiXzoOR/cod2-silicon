import AppKit
import Foundation

// Focused tests for the Discover/import and Servers ready-check view stores: the same intents
// the sheet and the card call, against private temporary homes, comparing exact bytes on disk.

@main struct ConfigDiscoverTests {
    static func require(_ condition: Bool, _ message: String, line: UInt = #line) {
        if !condition { print("FAIL: \(message) (line \(line))"); exit(1) }
    }
    static var folder: URL { Bundle.main.executableURL!.deletingLastPathComponent() }
    static func catalog() throws -> ConfigCatalog { try ConfigCatalog(data: Data(contentsOf: folder.appendingPathComponent("ConfigCatalog.json"))) }

    static func config(_ values: [String: String]) -> ConfigDocument {
        var text = "// generated by Call of Duty, do not modify\nunbindall\nbind w \"+forward\"\nbind MOUSE1 \"+attack\"\n"
        for name in values.keys.sorted(by: { $0.lowercased() < $1.lowercased() }) { text += "seta \(name) \"\(values[name]!)\"\n" }
        return ConfigDocument(data: Data(text.utf8), dialect: .cod2x)
    }
    /// The game writes every saved setting, so Main carries the mouse and texture values the rules read too.
    static let main = ["com_maxfps": "333", "sensitivity": "2.6", "r_gamma": "1.4", "cl_maxpackets": "60", "snaps": "20",
                       "cg_chatHeight": "4", "rate": "25000", "r_picmip": "3", "m_filter": "0", "cl_mouseAccel": "0", "r_picmip_manual": "0"]
    static let pub = ["com_maxfps": "125", "rate": "25000", "snaps": "20", "cl_maxpackets": "60", "m_filter": "0",
                      "cl_mouseAccel": "0", "r_picmip": "1", "r_picmip_manual": "0"]

    struct Home {
        let url: URL
        let store: ConfigProfileStore
        let session: ConfigStudioSession
        let studio: ConfigStudioModel
        func file(_ id: String) -> URL { url.appendingPathComponent("main/players/\(id)/config_mp.cfg") }
        func bytes(_ id: String) -> Data? { try? Data(contentsOf: file(id)) }
        var players: [String] { ((try? FileManager.default.contentsOfDirectory(atPath: url.appendingPathComponent("main/players").path)) ?? []).filter { !$0.hasPrefix(".") && !$0.hasSuffix(".txt") }.sorted() }
    }

    @MainActor static func makeHome(_ name: String, running: Bool = false) throws -> Home {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("cod2-discover-\(name)-\(UUID().uuidString.prefix(8))")
        let store = try ConfigProfileStore(homeURL: url, dialect: .cod2x)
        var meta = ConfigStudioMetadata(displayName: "Main"); meta.locks = ["r_gamma"]
        _ = try store.create(id: "Main", displayName: "Main", document: config(main), metadata: meta)
        try store.select(id: "Main", expectedActive: nil)
        _ = try store.create(id: "Scrim", displayName: "Scrim", document: config(main.merging(["com_maxfps": "250"]) { $1 }))
        _ = try store.create(id: "Pub", displayName: "Pub", document: config(pub))
        let session = try ConfigStudioSession(home: url, dialect: .cod2x, discoverGames: { running ? [4242] : [] })
        try session.refresh()
        if running { try session.reconcileGames([4242]) }
        let studio = ConfigStudioModel(session: session, dialect: .cod2x, catalog: { try catalog() })
        studio.loadCatalogNow()
        studio.announce = { _ in }
        return Home(url: url, store: store, session: session, studio: studio)
    }

    /// The sheet's real entry point: text is read and reviewed off the main thread.
    @MainActor static func reviewed(_ discover: ConfigDiscoverModel, _ text: String = DirectoryFixture.firstConfig) async -> ConfigImportReviewModel {
        discover.importText(text, dropped: false)
        guard let review = discover.review else { require(false, "the paste opened no review"); fatalError() }
        for _ in 0..<200 where { if case .loading = review.phase { return true }; return false }() { try? await Task.sleep(for: .milliseconds(25)) }
        if case .failed(let message) = review.phase { require(false, "review failed: \(message)") }
        require(review.session != nil, "review is ready")
        return review
    }
    @MainActor static func item(_ review: ConfigImportReviewModel, exact: String) -> ConfigImportItem {
        guard let item = review.items.first(where: { $0.exact.contains(exact) }) else { require(false, "no review row for \(exact)"); fatalError() }
        return item
    }

    @MainActor static func main() async {
        var homes: [URL] = []
        defer { homes.forEach { try? FileManager.default.removeItem(at: $0) } }
        do {
            try await reviewPresentationAndNewLoadout(&homes)
            try await existingLoadoutAndUndo(&homes)
            try await failedApplyKeepsBytes(&homes)
            try await directory(&homes)
            try await readyCheck(&homes)
        } catch { print("FAIL: \(error)"); exit(1) }
    }

    @MainActor static func reviewPresentationAndNewLoadout(_ homes: inout [URL]) async throws {
        let home = try makeHome("new"); homes.append(home.url)
        let discover = ConfigDiscoverModel(studio: home.studio, directory: ConfigDirectory(cacheURL: home.url.appendingPathComponent("directory/index.json")))
        let mainBefore = home.bytes("Main"), activeBefore = try home.store.activeSelection()
        let review = await reviewed(discover)
        require(review.targetID == nil && review.mode == .review, "Review into a new loadout is the default")
        let speed = item(review, exact: "sensitivity")
        require(speed.title == "Mouse speed" && speed.detail == "Set to 2.1" && speed.selected && speed.selectable, "plain setting row, ticked")
        if case .change = speed.section {} else { require(false, "safe settings are grouped changes") }
        require(!review.items.contains { if case .change = $0.section { return $0.title.contains("_") }; return false }, "no console names in change titles")
        for risky in ["connect 203", "seta name", "unbindall", "r_vsync"] {
            let row = item(review, exact: risky)
            require(row.section == .needsOK && row.selectable && !row.selected, "\(risky) needs an OK and starts unticked")
        }
        require(item(review, exact: "r_vsync").labels == ["Has no effect in CoD2"], "inert names are labelled")
        let secret = item(review, exact: "credential")
        require(secret.section == .never && !secret.selectable && !secret.exact.contains("sample-secret"), "credentials are blocked and redacted")
        require(item(review, exact: "exec practice").section == .never, "a file that wasn't included is never imported")
        require(item(review, exact: "r_mode").section == .machine, "display choices stay on this Mac")
        let safe = review.items.filter { if case .change = $0.section { return true }; return false }
        require(review.selectedCount == safe.count && review.applyTitle == "Apply \(safe.count) Changes", "the button names the selected changes")

        review.setMode(.everything)
        let eligible = review.items.filter(\.selectable)
        require(review.selectedCount == eligible.count && review.riskySelected.count == 4, "Import Everything ticks every eligible line")
        require(review.applyTitle == "Import All \(eligible.count), Including 4 Risky", "Import Everything names its risky lines")
        require(!review.items.contains { !$0.selectable && $0.selected }, "blocked lines stay out of Import Everything")
        review.toggle(item(review, exact: "connect 203").id)
        require(review.mode == .review && review.selectedCount == eligible.count - 1 && !item(review, exact: "connect 203").selected,
                "unticking in Import Everything returns to Review with the rest still ticked")
        review.setMode(.everything); review.setMode(.review)
        require(review.selectedCount == safe.count, "choosing Review again resets to the safe defaults")

        let expected = try review.session!.preview().document.serialized()
        guard let receipt = review.apply(undo: nil) else { require(false, "apply failed: \(review.applyError ?? "")"); return }
        require(receipt.profileID == "Pasted_config", "a new loadout named from the source")
        require(home.bytes("Pasted_config") == expected, "the new loadout holds exactly the reviewed bytes")
        let written = String(decoding: expected, as: UTF8.self)
        require(written.contains("seta sensitivity \"2.1\"") && !written.contains("connect") && !written.contains("sample-secret") && !written.contains("exec"),
                "only the ticked lines were written")
        let activeAfter = try home.store.activeSelection()
        require(home.bytes("Main") == mainBefore && activeAfter == activeBefore, "Main and the active loadout are untouched")
        let history = try home.store.history(id: "Pasted_config")
        require(history.count == 1 && history[0].source == .import, "one Import transaction")
        require(review.apply(undo: nil) == nil && home.bytes("Pasted_config") == expected, "a confirmed import can't apply twice")
        discover.finishImport(receipt, name: review.targetName, existing: false)
        require(discover.review == nil && discover.step == nil && home.session.current?.profile.id == "Pasted_config", "the imported loadout is shown")
        let activeShown = try home.store.activeSelection()
        require(activeShown == activeBefore, "showing it doesn't make it the active loadout")
        print("PASS: import review rows, defaults, Import Everything and a new-loadout apply with exact bytes")
    }

    @MainActor static func existingLoadoutAndUndo(_ homes: inout [URL]) async throws {
        let home = try makeHome("existing"); homes.append(home.url)
        let discover = ConfigDiscoverModel(studio: home.studio, directory: ConfigDirectory(cacheURL: home.url.appendingPathComponent("directory/index.json")))
        let before = home.bytes("Main")!
        let review = await reviewed(discover)
        review.setTarget("Main")
        require(review.targetID == "Main", "an existing loadout can be the destination")
        let gamma = item(review, exact: "r_gamma")
        require(gamma.section == .protected && !gamma.selectable && gamma.title == "Brightness stays 1.4", "a locked setting is protected")
        require(item(review, exact: "sensitivity").detail == "2.6 → 2.1", "changes show yours and theirs")
        let expected = try review.session!.preview().document.serialized()
        let undo = UndoManager(); undo.groupsByEvent = false
        undo.beginUndoGrouping()
        guard review.apply(undo: undo) != nil else { require(false, "apply failed: \(review.applyError ?? "")"); return }
        undo.endUndoGrouping()
        require(home.bytes("Main") == expected, "Main holds exactly the reviewed bytes")
        require(ConfigDocument(data: expected, dialect: .cod2x).effectiveSetting(named: "r_gamma") == "1.4", "the lock kept brightness")
        let imported = try home.store.history(id: "Main").first?.source
        require(imported == .import, "one Import transaction")
        require(undo.canUndo && undo.undoActionName == "Import", "Undo Import is offered")
        undo.undo()
        require(home.bytes("Main") == before, "Undo restores the exact bytes from before")
        let restored = try home.store.history(id: "Main").first?.source
        require(restored == .restore, "the undo is its own History transaction")
        print("PASS: importing into a locked existing loadout, then Undo, with exact bytes")
    }

    @MainActor static func failedApplyKeepsBytes(_ homes: inout [URL]) async throws {
        let home = try makeHome("conflict"); homes.append(home.url)
        let discover = ConfigDiscoverModel(studio: home.studio, directory: ConfigDirectory(cacheURL: home.url.appendingPathComponent("directory/index.json")))
        let review = await reviewed(discover)
        review.setTarget("Main")
        let read = try home.store.read(id: "Main")
        try home.store.update(id: "Main", document: config(main.merging(["cg_chatHeight": "6"]) { $1 }), expected: read.version, summary: "Changed elsewhere")
        let changed = home.bytes("Main"), rows = try home.store.history(id: "Main").count
        require(review.apply(undo: nil) == nil && review.receipt == nil, "a stale review refuses to apply")
        require(review.applyError?.contains("changed while you were reviewing") == true, "the sheet says why")
        let rowsAfter = try home.store.history(id: "Main").count
        require(home.bytes("Main") == changed && rowsAfter == rows, "a failed apply keeps the prior bytes and History")

        let running = try makeHome("running", running: true); homes.append(running.url)
        let blocked = ConfigDiscoverModel(studio: running.studio, directory: ConfigDirectory(cacheURL: running.url.appendingPathComponent("directory/index.json")))
        let pending = await reviewed(blocked)
        let players = running.players
        require(pending.apply(undo: nil) == nil && pending.applyError?.contains("read-only") == true, "no import while the game runs")
        require(running.players == players, "nothing was created while the game runs")
        print("PASS: a stale or game-owned import keeps the exact prior bytes and leaves the review open")
    }

    @MainActor static func directory(_ homes: inout [URL]) async throws {
        let home = try makeHome("directory"); homes.append(home.url)
        let cache = home.url.appendingPathComponent("directory/index.json")
        let discover = ConfigDiscoverModel(studio: home.studio, directory: ConfigDirectory(cacheURL: cache))
        await discover.reload()
        if case .unavailable = discover.state {} else { require(false, "the production directory is honestly unavailable") }
        require(discover.entries.isEmpty && discover.saved.isEmpty && !FileManager.default.fileExists(atPath: cache.path), "no players, no Saved, no cache written")

        let fixtureCache = home.url.appendingPathComponent("fixture/index.json")
        discover.use(try DirectoryFixture.directory(cacheURL: fixtureCache))
        await discover.reload()
        require(discover.shelves.map(\.id) == ["2005–2008", "2009–2012"], "shelves follow the signed entries' eras")
        discover.query = "sniper"
        require(discover.matches.map(\.id) == ["player-2"], "search matches role")
        discover.query = ""
        discover.setSaved("player-2", true)
        require(discover.isSaved("player-2") && discover.saved.count == 1, "Saved keeps a verified bookmark")
        let mainBefore = home.bytes("Main")
        discover.loadDetail("player-1")
        for _ in 0..<200 where { if case .loading = discover.detail?.phase { return true }; return false }() { try? await Task.sleep(for: .milliseconds(25)) }
        guard case .ready(let summary)? = discover.detail?.phase else { require(false, "player detail loads"); return }
        require(summary.comparedWith == "Main", "compared with the active loadout")
        require(summary.changes.contains { $0.title == "Your brightness stays 1.4" && $0.locked }, "locks are acknowledged")
        require(summary.changes.contains { $0.title == "You’ll turn about 19% slower" && $0.detail.contains("DPI") }, "no distance claim without a DPI")
        require(summary.needsOK > 0 && summary.never > 0, "risky and blocked lines are counted")
        require(home.bytes("Main") == mainBefore, "looking at a player writes nothing")
        discover.tryEntry(discover.entry("player-1")!)
        guard let review = discover.review else { require(false, "Try this setup opens a review"); return }
        for _ in 0..<200 where { if case .loading = review.phase { return true }; return false }() { try? await Task.sleep(for: .milliseconds(25)) }
        require(review.provenance.signed && review.provenance.credit == "[Player 1]" && review.targetID == nil, "a signed entry reviews into a new loadout")
        require(item(review, exact: "r_mode").section == .machine, "a Windows entry keeps display choices on this Mac")
        discover.closeImport()
        require(home.bytes("Main") == mainBefore && home.players == ["Main", "Pub", "Scrim"], "closing the review writes nothing")
        print("PASS: unavailable production directory, signed fixture, Saved, player comparison and Try this setup")
    }

    @MainActor static func readyCheck(_ homes: inout [URL]) async throws {
        let home = try makeHome("ready"); homes.append(home.url)
        let model = LauncherModel(snapshot: true)
        model.studio.attach(home.session)
        model.studio.loadCatalogNow()
        model.studio.announce = { _ in }
        let competitive = GameServer(address: "203.0.113.200:28960", fields: ["sv_hostname": "Sample league", "mapname": "mp_toujane", "protocol": "120",
            "shortversion": "1.4.6.8", "fs_game": "", "g_competitive": "1"], ping: 40, players: [], observedAt: Date())
        model.servers.append(competitive)
        model.selectedServer = competitive.address
        let check = ServerReadyCheckModel()
        check.evaluate(model, address: competitive.address)
        let issue = check.presentation(model, loadout: "Main")
        // Addresses differ from the preview model's seeded servers, so the check reads these fresh replies.
        require(check.report?.status == .needsChanges && issue.kind == .needsChange && issue.canFix,
                "a cited competitive limit needs a change: \(check.report.map { "\($0.status) \($0.fixes) \($0.limitations)" } ?? "no report")")
        require(issue.title == "Your “Main” loadout needs one change here", "plain title: \(issue.title)")
        require(issue.fixes == ["Frame rate cap 250 fps instead of 333 fps"], "the fix in words: \(issue.fixes)")
        require(issue.lines.contains { $0.tone == .information && $0.text.hasPrefix("The server sets your") }, "server-set values are neutral")
        require(!issue.lines.contains { $0.text.contains("com_maxfps") }, "no console names outside Details")

        let snapshot = { () throws -> [Data?] in [home.bytes("Main"), try? Data(contentsOf: home.url.appendingPathComponent("main/players/Main/studio.json")),
                                                  try? Data(contentsOf: home.url.appendingPathComponent("main/players/active.txt"))] }
        let before = try snapshot(), rows = try home.store.history(id: "Main").count, players = home.players
        check.fix(model, address: competitive.address)
        require(model.serverConnection.overrides == ["com_maxfps": "250"], "the fix is staged for this connection")
        let afterFix = try snapshot(), rowsAfterFix = try home.store.history(id: "Main").count
        require(afterFix == before && rowsAfterFix == rows && home.players == players,
                "Fix for this server only never writes the loadout, its History or the active selection")
        check.useLoadout("Scrim", model: model, address: competitive.address)
        require(model.serverConnection.profileID == "Scrim" && model.serverConnection.overrides.isEmpty && check.report?.profileID == "Scrim",
                "another loadout for this connection, reviewed in place")
        let afterChoice = try snapshot()
        require(afterChoice == before && ReadyCheckCard.deployTitle(model, competitive) == "Deploy with Scrim", "choosing it changes nothing on disk")
        check.undo(model, address: competitive.address)
        require(model.serverConnection.profileID == nil && model.serverConnection.overrides.isEmpty, "Undo returns to the active loadout")

        let stale = GameServer(address: "198.51.100.200:28960", fields: competitive.fields, ping: 30, players: [])
        model.servers.append(stale)
        check.evaluate(model, address: stale.address)
        let unknown = check.presentation(model, loadout: "Main")
        require(unknown.kind == .unknown && unknown.tone == .unknown && !unknown.canFix && unknown.title == "We don’t know this server’s rules",
                "unobserved rules are unknown, never a pass")

        let public14 = GameServer(address: "192.0.2.200:28960", fields: ["sv_hostname": "Sample pub", "protocol": "120", "shortversion": "1.4.6.8",
            "fs_game": "", "g_competitive": "0"], ping: 20, players: [], observedAt: Date())
        model.servers.append(public14)
        check.useLoadout("Pub", model: model, address: public14.address)
        let match = check.presentation(model, loadout: "Pub")
        require(check.report?.status == .matchesKnownRules && match.kind == .matches && match.message?.contains("Only those settings are checked") == true,
                "a match is scoped to the listed rules")

        let bare = LauncherModel(snapshot: true)
        let none = ServerReadyCheckModel()
        none.evaluate(bare, address: competitive.address)
        require(none.report == nil && none.presentation(bare, loadout: "Main").kind == .unavailable, "no Configs session reads as unavailable")
        print("PASS: ready check in plain words; fixes and per-connection loadouts never touch profile bytes")
    }
}
