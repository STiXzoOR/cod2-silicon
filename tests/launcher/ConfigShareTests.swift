    /// The client against the stand-in service: what it sends, and each reply it can get.
    static func standIn() async throws {
        guard let address = environment["COD2_SHARE_URL"], let base = URL(string: address), base.host == "127.0.0.1",
              let log = environment["COD2_SHARE_RECORD"] else {
            print("FAIL: config_share.sh starts the stand-in and sets COD2_SHARE_URL and COD2_SHARE_RECORD"); exit(1)
        }
        require(ConfigShareClient.base() == base, "the client takes COD2_SHARE_URL")
        let client = ConfigShareClient(base: base)
        func script(_ kind: String, _ value: String) async throws {
            var request = URLRequest(url: base.appendingPathComponent("standin"))
            request.httpMethod = "POST"; request.httpBody = ConfigShareClient.encode([kind: value])
            request.setValue("application/json", forHTTPHeaderField: "Content-Type")
            _ = try await URLSession.shared.data(for: request)
        }
        let prepared = try await ConfigShare.prepare(Data(loadout.utf8), catalog: try catalog())
        let body = ConfigShare.requestBody(prepared, name: "morrow", dialect: .cod2x, app: "0.4.1")

        try await script("share", "sent")
        guard case .sent(let receipt) = await client.share(body) else { require(false, "sent"); return }
        require(receipt.url.absoluteString == ConfigShareClient.pulls + "\(receipt.request)" && receipt.id == "morrow" && receipt.token.count == 64, "the receipt")
        let lines = try String(contentsOfFile: log, encoding: .utf8).split(separator: "\n")
        let last = try JSONSerialization.jsonObject(with: Data(lines.last!.utf8)) as? [String: Any]
        let sent = last?["body"] as? [String: Any]
        require(last?["path"] as? String == "/api/configs/share", "the share endpoint was called")
        require(sent?["config"] as? String == prepared.text && sent?["name"] as? String == "morrow" && sent?["v"] as? Int == 1, "the stand-in got the cleaned text and the name")
        require(!(sent?["config"] as? String ?? "").contains("sample-secret") && !(sent?["config"] as? String ?? "").contains("Morrow\""), "nothing personal was sent")
        // The stand-in's token is HMAC(secret, "<request>:<sha256 of config>"): the bytes it hashed are the ones we sent.
        require(ConfigShare.sha256(Data((sent?["config"] as? String ?? "").utf8)) == prepared.digest, "the record's SHA-256 is of exactly what was sent")

        for (step, expected) in [("already", ConfigShareReply.already), ("limit", .limit(everyone: false)), ("limit-day", .limit(everyone: true)),
                                 ("unavailable", .unreachable), ("invalid", .unreachable), ("too-large", .tooLarge), ("drop", .unreachable)] {
            try await script("share", step)
            let reply = await client.share(body)
            require(reply == expected, "\(step) → \(reply)")
        }
        // A 400 or an unexpected reply is never retried by itself: one request each.
        let before = try String(contentsOfFile: log, encoding: .utf8).split(separator: "\n").count
        try await script("share", "invalid")
        _ = await client.share(body)
        let after = try String(contentsOfFile: log, encoding: .utf8).split(separator: "\n").count
        require(after - before == 2, "one script change and exactly one share request (\(after - before) lines)")

        // Slow: the stand-in waits 3 seconds. A short timeout is couldn't reach; Cancel stops it.
        try await script("share", "slow")
        var quick = client; quick.timeout = 1
        let timedOut = await quick.share(body)
        require(timedOut == .unreachable, "a timeout is couldn't reach (\(timedOut))")
        let task = Task { await client.share(body) }
        try await Task.sleep(for: .milliseconds(300))
        task.cancel()
        let started = Date()
        let cancelled = await task.value
        require(cancelled == .cancelled && Date().timeIntervalSince(started) < 2, "Cancel stops the request at once (\(cancelled))")

        try await script("withdraw", "withdrawn")
        require(await client.withdraw(request: 128, token: receipt.token) == .withdrawn, "withdrawn")
        let withdrawLine = try String(contentsOfFile: log, encoding: .utf8).split(separator: "\n").last!
        let withdrawBody = (try JSONSerialization.jsonObject(with: Data(withdrawLine.utf8)) as? [String: Any])?["body"] as? [String: Any]
        require(withdrawBody?["request"] as? Int == 128 && withdrawBody?["token"] as? String == receipt.token && withdrawBody?["v"] as? Int == 1, "the withdraw request")
        try await script("withdraw", "removal")
        require(await client.withdraw(request: 128, token: receipt.token) == .removal(URL(string: ConfigShareClient.pulls + "129")!), "removal")
        try await script("withdraw", "forbidden")
        require(await client.withdraw(request: 128, token: receipt.token) == .forbidden, "forbidden")
        try await script("withdraw", "unavailable")
        require(await client.withdraw(request: 128, token: receipt.token) == .unreachable, "unavailable")
        try await script("withdraw", "drop")
        require(await client.withdraw(request: 128, token: receipt.token) == .unreachable, "drop")
        print("PASS: against the stand-in: sent, already, both limits, unavailable, 400, 413, a dropped connection, a timeout, Cancel, and every withdraw reply")

        try await centerFlow(base: base)
    }

    /// Stop Sharing through the center: a failed withdraw keeps the record; a good one forgets it.
    @MainActor static func centerFlow(base: URL) async throws {
        let home = URL(fileURLWithPath: environment["COD2_SHARE_TEST_HOME"] ?? NSTemporaryDirectory()).appendingPathComponent("center-\(UUID().uuidString.prefix(8))")
        defer { try? FileManager.default.removeItem(at: home) }
        let center = ConfigShareCenter(home: home)
        center.client = ConfigShareClient(base: base)
        let record = ConfigShareRecord(request: 128, url: URL(string: ConfigShareClient.pulls + "128")!, token: String(repeating: "d", count: 64),
                                       sent: "2026-11-21", sha256: String(repeating: "e", count: 64), name: "morrow")
        try center.remember(record, loadout: "Main")
        require(ConfigShareCenter(home: home).record("Main") == record && ConfigShareCenter(home: home).rememberedName == "morrow", "a new center reads the record and the name")
        let studio = ConfigStudioModel(session: nil)
        var announced: [String] = []
        studio.announce = { announced.append($0) }
        let profile = ConfigProfile(id: "Main", displayName: "Main", isActive: true)
        func script(_ value: String) async throws {
            var request = URLRequest(url: base.appendingPathComponent("standin"))
            request.httpMethod = "POST"; request.httpBody = ConfigShareClient.encode(["withdraw": value])
            _ = try await URLSession.shared.data(for: request)
        }
        func waitWithdraw() async throws {
            for _ in 0..<200 where !center.withdrawing.isEmpty { try await Task.sleep(for: .milliseconds(20)) }
            try await Task.sleep(for: .milliseconds(50))
        }
        try await script("unavailable")
        center.withdraw(profile, studio: studio)
        require(center.withdrawing.contains("main"), "Stop Sharing is on its way")
        try await waitWithdraw()
        require(center.record("Main") == record && ConfigShareRecordFile.load(home: home).record("Main") == record, "a failed withdraw keeps the record")
        require(studio.failure?.title == "Couldn’t stop sharing Main" && studio.failure?.message.hasPrefix("Couldn’t reach cod2unbound.com") == true, "and says so")
        require(announced.last?.hasPrefix("Couldn’t stop sharing Main") == true, "the failure is announced")
        studio.failure = nil
        try await script("withdrawn")
        center.withdraw(profile, studio: studio)
        try await waitWithdraw()
        require(center.record("Main") == nil && ConfigShareRecordFile.load(home: home).record("Main") == nil, "a withdraw forgets the record")
        require(studio.failure == nil && studio.notice == "Main is no longer shared.", "and says so: \(studio.notice ?? "nil")")
        print("PASS: Stop Sharing keeps the record when it fails and forgets it when the request is withdrawn")
    }
