    static func cleaning() async throws {
        let prepared = try await ConfigShare.prepare(Data(loadout.utf8), catalog: try catalog())
        let sent = prepared.text
        let expected = """
        unbindall
        bind TAB "+scores"
        bind SPACE "+gostand"
        bind w "+forward"
        bind s "+back"
        bind MOUSE1 "+attack"
        seta cl_maxpackets "100"
        seta com_maxfps "250"
        seta r_gamma "1.4"
        seta r_picmip "2"
        seta rate "25000"
        seta sensitivity "2.6"
        seta snaps "30"

        """
        require(sent == expected, "the cleaned text keeps settings and binds in order and nothing else:\n\(sent)")
        require(prepared.settings == 7 && prepared.binds == 5 && prepared.lines == 13, "counts: \(prepared.settings) settings, \(prepared.binds) binds, \(prepared.lines) lines")
        let left = Dictionary(uniqueKeysWithValues: prepared.leftOut.map { ($0.shown, $0) })
        require(prepared.leftOut.count == 6, "six lines left out, the comment not counted: \(prepared.leftOut.map(\.shown))")
        require(left["seta name \"^3Sgt. ^7Morrow\""]?.reasons.contains("identity") == true, "the name is left out as identity")
        require(left["seta name \"^3Sgt. ^7Morrow\""]?.because == "Your name or who you are in the game", "identity in plain words")
        require(left["seta rconpassword …"]?.reasons.contains("credential") == true, "a password is left out and its value never shown: \(left.keys.sorted())")
        require(!prepared.leftOut.contains { $0.shown.contains("sample-secret") }, "the secret never appears in the preview")
        require(left["bind F1 \"say good game\""]?.because == "Chat or a message to other players", "chat in plain words")
        require(left["bind F5 \"connect 203.0.113.24:28960\""]?.reasons.contains("connect") == true, "a server address is left out")
        require(left["bind MOUSE4 \"+attack;wait;-attack\""]?.reasons.contains("macro") == true, "a timed macro is left out")
        require(left["seta sv_hostname \"Scrim night\""]?.because == "A setting for hosting a server", "hosting settings are left out")
        require(prepared.problem == nil, "13 lines can be shared")
        require(prepared.reasons == prepared.reasons.sorted() && prepared.reasons.contains("identity") && prepared.reasons.allSatisfy { $0.range(of: "^[A-Za-z]{1,32}$", options: .regularExpression) != nil },
                "left reasons are the review's names: \(prepared.reasons)")
        // The same cleaning as the catalogue tool: ConfigClean keeps the same bytes before the service's rules.
        let clean = try await ConfigClean.clean(Data(loadout.utf8), catalog: try catalog())
        require(clean.bytes == prepared.bytes && clean.comments == 1 && clean.leftOut.count == 6, "Share sends exactly what ConfigClean keeps here")
        print("PASS: cleaning keeps \(prepared.lines) lines and leaves out \(prepared.leftOut.count) with reasons")

        // What the game loads: the config, then the advanced binds' companion file.
        let read = ConfigProfileRead(profile: .init(id: "Main", displayName: "Main", isActive: true),
                                     document: ConfigDocument(data: Data("seta a \"1\"".utf8), dialect: .cod2x),
                                     metadata: ConfigStudioMetadata(displayName: "Main"),
                                     version: .init(config: Data("seta a \"1\"".utf8), metadata: nil, chain: Data("bind m \"toggle cg_drawFPS 0 1\"\n".utf8)))
        require(ConfigShare.loadoutText(read) == Data("seta a \"1\"\nbind m \"toggle cg_drawFPS 0 1\"\n".utf8), "the loadout's text is its config and then its companion file")
    }

    static func tenLineRule() async throws {
        func text(_ count: Int) -> Data {
            let names = ["sensitivity", "com_maxfps", "r_gamma", "r_picmip", "rate", "snaps", "cl_maxpackets", "cg_chatHeight", "snd_volume", "in_rawmouse", "cg_drawFPS"]
            return Data((names.prefix(count).enumerated().map { "seta \($0.element) \"\($0.offset)\"" } + ["seta name \"someone\""]).joined(separator: "\n").utf8 + Data([10]))
        }
        let nine = try await ConfigShare.prepare(text(9), catalog: try catalog())
        require(nine.lines == 9 && nine.problem == .nothingToShare, "nine lines left is nothing to share (\(nine.lines))")
        let ten = try await ConfigShare.prepare(text(10), catalog: try catalog())
        require(ten.lines == 10 && ten.problem == nil, "ten lines can be shared (\(ten.lines))")
        let empty = try await ConfigShare.prepare(Data(), catalog: try catalog())
        require(empty.problem == .nothingToShare, "an empty loadout has nothing to share")
        var large = ConfigShare.Prepared(bytes: Data(repeating: 65, count: 65536), settings: 0, binds: 0, leftOut: [], reasons: [], lines: 10)
        require(large.problem == .tooLarge, "65,536 bytes is more than the service takes")
        large.bytes = Data(repeating: 65, count: 65535)
        require(large.problem == nil, "65,535 bytes is allowed")
        print("PASS: fewer than ten cleaned lines is nothing to share; over 65,535 bytes is too large")
    }

    static func serviceRules() {
        func refusal(_ line: String) -> String? { ConfigShare.ServiceRules.refusal(Data(line.utf8)) }
        require(refusal("seta sensitivity \"2.6\"") == nil, "a setting passes")
        require(refusal("bind w \"+forward\"") == nil && refusal("unbind w") == nil && refusal("unbindall") == nil, "binds pass")
        require(refusal("seta cl_anglespeedkey \"1.5\"") == nil, "key inside a word is not a secret")
        require(refusal("seta cl_key \"x\"") == "credential" && refusal("seta cdkey1 \"x\"") == "credential", "key parts and cdkey are secrets")
        require(refusal("seta g_password \"x\"") == "hosting" && refusal("seta sv_hostname \"x\"") == "hosting", "hosting names")
        require(refusal("seta cl_guid \"x\"") == "identity", "cl_guid is identity")
        require(refusal("seta cg_customText \"say hello\"") == "chat", "a value that says something")
        require(refusal("bind k \"exec other.cfg\"") == "unresolvedExec" && refusal("bind k \"rcon_login x\"") == "remoteConsole", "script words")
        require(refusal("seta a \"1\"; seta b \"2\"") == "notAccepted" && refusal("seta a \"1\" // note") == "notAccepted", "one command per line, no comments")
        require(refusal("seta a \"é\"") == "notAccepted" && refusal("seta a \"" + String(repeating: "x", count: 1030) + "\"") == "notAccepted", "ASCII and 1,024 bytes")
        require(refusal("vstr cycle") == "notAccepted" && refusal("seta x") == "notAccepted", "only complete settings and binds")
        print("PASS: the service's line rules")
    }

