    static func replies() {
        let token = String(repeating: "a", count: 64)
        func json(_ object: Any) -> Data { (try? JSONSerialization.data(withJSONObject: object)) ?? Data() }
        let good = json(["request": 128, "url": "https://github.com/cod2unbound/cod2-configs/pull/128", "id": "morrow", "token": token])
        require(ConfigShareClient.shareReply(status: 201, body: good)
                == .sent(.init(request: 128, url: URL(string: "https://github.com/cod2unbound/cod2-configs/pull/128")!, id: "morrow", token: token)), "201 is sent")
        require(ConfigShareClient.shareReply(status: 201, body: json(["request": 128, "url": "https://example.com/pull/128", "id": "m", "token": token])) == .unreachable,
                "a 201 that points anywhere but the catalogue's pull requests is unexpected")
        require(ConfigShareClient.shareReply(status: 201, body: json(["request": 129, "url": "https://github.com/cod2unbound/cod2-configs/pull/128", "id": "m", "token": token])) == .unreachable,
                "a 201 whose address names another request is unexpected")
        require(ConfigShareClient.shareReply(status: 201, body: json(["request": 128, "url": "https://github.com/cod2unbound/cod2-configs/pull/128", "id": "m", "token": "short"])) == .unreachable,
                "a 201 without a 64-hex token is unexpected")
        require(ConfigShareClient.shareReply(status: 409, body: json(["error": "already"])) == .already, "409 already")
        require(ConfigShareClient.shareReply(status: 429, body: json(["error": "limit", "scope": "network"])) == .limit(everyone: false), "429 network")
        require(ConfigShareClient.shareReply(status: 429, body: json(["error": "limit", "scope": "day"])) == .limit(everyone: true), "429 day")
        require(ConfigShareClient.shareReply(status: 413, body: json(["error": "invalid", "field": "config"])) == .tooLarge, "413")
        for status in [400, 403, 404, 405, 500, 503, 200, 302] {
            require(ConfigShareClient.shareReply(status: status, body: json(["error": "invalid", "field": "name"])) == .unreachable, "\(status) is shown as couldn't reach")
        }
        require(ConfigShareClient.shareReply(status: 409, body: Data("<html>".utf8)) == .unreachable, "a 409 that isn't the contract's is unexpected")
        require(ConfigShareClient.withdrawReply(status: 200, body: json(["state": "withdrawn"])) == .withdrawn, "withdrawn")
        require(ConfigShareClient.withdrawReply(status: 200, body: json(["state": "removal", "url": "https://github.com/cod2unbound/cod2-configs/pull/130"]))
                == .removal(URL(string: "https://github.com/cod2unbound/cod2-configs/pull/130")!), "removal")
        require(ConfigShareClient.withdrawReply(status: 403, body: json(["error": "forbidden"])) == .forbidden, "forbidden")
        require(ConfigShareClient.withdrawReply(status: 503, body: json(["error": "unavailable"])) == .unreachable, "503 on withdraw")
        print("PASS: every reply in the contract maps to its state; anything else is couldn't reach")
    }

