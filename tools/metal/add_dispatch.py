#!/usr/bin/env python3
"""Add native dispatch guards to shim entry points; preserve their GL bodies.

The generated guards pass addresses of typed arguments (including floats and
function pointers), so no register ABI is guessed or narrowed. --check proves
all object entry points have their exact generated guard. Run only inside the
current checkout.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
FILES = ['CDirect3D', 'CDirect3DDevice', 'CDirect3DSwapChain', 'CDirect3DSurface',
         'CDirect3DTexture', 'CDirect3DCubeTexture', 'CDirect3DVolumeTexture',
         'CDirect3DVertexBuffer', 'CDirect3DIndexBuffer', 'CDirect3DVertexDeclaration',
         'CDirect3DVertexShader', 'CDirect3DPixelShader', 'CFence', 'CMemoryBuffer',
         'CVAOPacket', 'CVertexArrays', 'COpenGLVAO', 'COpenGL', 'd3d9_real']
PATTERN = re.compile(r'^([A-Za-z_][\w *]*?[\s*])(\w+)\(([^;{}]*?)\)\s*\{', re.M)
PREFIX = ('CDirect3D', 'COpenGL', 'CFence_', 'CMemoryBuffer_', 'CVAOPacket_', 'CVertexArrays_', 'Direct3DCreate9', 'CreateVolumeTexture')

def parameters(text):
    parts, start, depth = [], 0, 0
    for i, char in enumerate(text):
        depth += char in '(['
        depth -= char in ')]'
        if char == ',' and not depth:
            parts.append(text[start:i].strip()); start = i + 1
    parts.append(text[start:].strip())
    return [x for x in parts if x and x != 'void']

def name(part):
    m = re.search(r'\(\s*\*\s*(\w+)\s*\)', part)
    return m[1] if m else re.findall(r'\w+', re.sub(r'\[[^]]*\]', '', part))[-1]

p = argparse.ArgumentParser()
p.add_argument('--check', action='store_true')
a = p.parse_args()
entries = []
for file in FILES:
    path = ROOT / 'src/Mac/DirectX_9' / (file + '.c')
    source = path.read_text()
    insertions = []
    for m in PATTERN.finditer(source):
        ret, fn, params = m.groups()
        if 'static' in ret or not (fn.startswith(PREFIX) or (fn.startswith(('ZN', 'ZTh')) and any(x in fn for x in ['CDirect3D', 'COpenGL', 'CMemoryBuffer', 'CVAOPacket', 'CVertexArrays']))):
            continue
        if source[m.end():].startswith('}'):
            continue
        ret = ret.replace('COD2_FORCE_ALIGN_ARG_POINTER\n', '').strip()
        names = [name(x) for x in parameters(params)]
        receiver = names[0] if names and ('*' in parameters(params)[0]) and not fn.startswith(('Direct3DCreate9', 'CreateVolumeTexture')) else 'NULL'
        entries.append(dict(method=fn, file=str(path.relative_to(ROOT)), result=ret, arguments=names))
        args = ', '.join('&' + x for x in names) or 'NULL'
        body = '\n#if MAC_METAL_NATIVE\n    const void *macArguments[] = { ' + args + ' };\n'
        if ret == 'void':
            body += f'    if (MacShim_Dispatch("{fn}", {receiver}, macArguments, NULL, 0))\n        return;\n'
        else:
            body += f'    {ret} macResult = {{ 0 }};\n    if (MacShim_Dispatch("{fn}", {receiver}, macArguments, &macResult, sizeof(macResult)))\n        return macResult;\n'
        body += '#endif\n'
        after = source[m.end():]
        if after.startswith('\n#if MAC_METAL_NATIVE'):
            if not after.startswith(body):
                raise SystemExit('malformed native dispatch: ' + fn)
            continue
        if a.check:
            raise SystemExit('unguarded: ' + fn)
        insertions.append((m.end(), body))
    if not a.check:
        for offset, body in reversed(insertions):
            source = source[:offset] + body + source[offset:]
        if '#include "Mac/Metal/shim_dispatch.h"' not in source:
            source = '#include "Mac/Metal/shim_dispatch.h"\n' + source
        path.write_text(source)
manifest = ROOT / 'tools/metal/shim_methods.json'
result_types = ROOT / 'src/Mac/Metal/metal_hresult.inc'
typed_entries = '/* Generated by tools/metal/add_dispatch.py; native HRESULT entries. */\n'
typed_entries += ''.join('MAC_METAL_HRESULT_ENTRY("' + x['method'] + '")\n'
                         for x in entries if x['result'].startswith('HRESULT'))
if not a.check:
    manifest.write_text(json.dumps(entries, indent=2) + '\n')
    result_types.write_text(typed_entries)
else:
    assert json.loads(manifest.read_text()) == entries
    assert result_types.read_text() == typed_entries
print(f'{len(entries)} shim entry points have native dispatch; GL bodies preserved')
